const fmt = (n) =>
  new Intl.NumberFormat('en-US', { style: 'currency', currency: 'USD', maximumFractionDigits: 0 }).format(n)

const ResultCard = ({ result }) => {
  const predicted = result.predicted_price ?? result.prediction ?? result.price ?? 0
  const low  = result.range_low  ?? predicted * 0.91
  const high = result.range_high ?? predicted * 1.09

  return (
    <div
      className="mt-6 border border-teal-500 dark:border-teal-600 rounded-xl overflow-hidden bg-teal-50 dark:bg-teal-900/20"
      style={{ animation: 'enter 0.4s cubic-bezier(0.22,1,0.36,1) both' }}
    >
      <div className="bg-teal-600 dark:bg-teal-700 px-6 py-3 flex items-center justify-between">
        <span className="text-white text-xs font-semibold tracking-widest uppercase">Predicted Median Value</span>
        <span className="text-teal-200 text-xs">Model confidence ±9%</span>
      </div>

      <div className="px-6 py-6">
        <p className="font-serif text-ink-900 dark:text-white leading-none" style={{ fontSize: 'clamp(2.4rem, 5vw, 3rem)' }}>
          {fmt(predicted)}
        </p>
        <p className="text-ink-500 dark:text-ink-400 text-sm mt-2">
          Estimated range:{' '}
          <span className="text-ink-700 dark:text-white font-medium">{fmt(low)}</span>
          {' – '}
          <span className="text-ink-700 dark:text-white font-medium">{fmt(high)}</span>
        </p>

        <div className="mt-5 pt-5 border-t border-teal-200 dark:border-teal-800 grid grid-cols-2 gap-4">
          <div>
            <p className="text-[10px] uppercase tracking-widest text-ink-400 dark:text-dark-600 mb-1">Lower bound (−9%)</p>
            <p className="text-ink-700 dark:text-ink-300 font-medium text-sm">{fmt(low)}</p>
          </div>
          <div>
            <p className="text-[10px] uppercase tracking-widest text-ink-400 dark:text-dark-600 mb-1">Upper bound (+9%)</p>
            <p className="text-ink-700 dark:text-ink-300 font-medium text-sm">{fmt(high)}</p>
          </div>
        </div>

        <p className="mt-5 text-[11px] text-ink-400 dark:text-dark-600 leading-relaxed">
          This estimate is generated by a Random Forest regression model trained on the 1990 California Housing dataset. It reflects median home values per census block group and should not be used as a formal appraisal.
        </p>
      </div>
    </div>
  )
}

export default ResultCard
